    /**
     * v323：Gemini 网页版（浏览器 cookie 直连 gemini.google.com）。
     *
     * 与 [GeminiOAuth]（反重力 / Code Assist）是两条完全独立的通道：
     * - OAuth 走 Google 官方客户端协议，稳定但需要账号在反重力可用；
     * - 网页版用浏览器登录后的 cookie 直接调 Gemini 网页内部接口，不需要 key，
     *   但属于非公开接口，协议可能随 Google 前端改动而失效。
     *
     * cookie 存的是浏览器里 gemini.google.com 的 Cookie 原文（至少包含
     * `__Secure-1PSID` 与 `__Secure-1PSIDTS`，有 `SAPISID` 会额外带认证头）。
     */
    @Serializable
    @SerialName("gemini_web")
    data class GeminiWeb(
        override var id: Uuid = Uuid.random(),
        override var enabled: Boolean = true,
        override var name: String = "Gemini 网页版",
        override var models: List<Model> = emptyList(),
        override val customHeaders: List<CustomHeader> = emptyList(),
        @Transient override val builtIn: Boolean = false,
        @Transient override val description: @Composable () -> Unit = {},
        @Transient override val shortDescription: @Composable () -> Unit = {},
        /** 浏览器 Cookie 原文，例如 `__Secure-1PSID=...; __Secure-1PSIDTS=...; SAPISID=...` */
        val cookie: String = "",
        /** 可选：手动指定网页前端的构建标签（bl）；留空自动从 /app 页面解析 */
        val buildLabel: String = "",
        /**
         * v1016：**登录这套 Cookie 时用的浏览器标识**，一键登录会自动填进来。
         *
         * 为什么要有这个字段：网页会话 Cookie 在 Google 那边是和"登录时用的浏览器"绑在一起的。
         * 本类的 cookie 可以由用户在桌面浏览器里复制，也可以由应用内登录页抓出来，
         * 而请求侧如果一直固定发同一个写死的桌面 UA，就和手机上的登录态自相矛盾 ——
         * 表现是"Cookie 明明是对的，一调用就 403 / CookieMismatch"。
         * 留空时退回内置默认 UA，老配置与手动粘贴的行为完全不变。
         */
        val userAgent: String = "",
    ) : ProviderSetting() {

        override fun copyProvider(
            id: Uuid,
            enabled: Boolean,
            name: String,
            models: List<Model>,
            customHeaders: List<CustomHeader>,
            builtIn: Boolean,
            description: @Composable () -> Unit,
            shortDescription: @Composable () -> Unit,
        ): ProviderSetting {
